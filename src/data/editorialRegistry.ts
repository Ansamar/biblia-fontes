const PLACEHOLDER_PATTERNS = [/in preparazione/i,/da definire/i,/non ancora disponibile/i,/attribuzione registrata/i,/scheda introduttiva/i,/dati compositivi/i,/contesto storico pertinente/i];
function textFromUnknown(value: unknown): string { if(value==null)return ''; if(typeof value==='string'||typeof value==='number')return String(value).trim(); if(Array.isArray(value))return value.map(textFromUnknown).filter(Boolean).join(' · '); if(typeof value==='object'){const v=value as Record<string,unknown>;return textFromUnknown(v.descrizione??v.motivazione??v.etichetta??v.citazione??v.titolo??v.nome??v.nota);} return ''; }
function usable(value: unknown){const text=textFromUnknown(value);return Boolean(text)&&!PLACEHOLDER_PATTERNS.some(p=>p.test(text));}
